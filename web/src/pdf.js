const PDFDocument = require('pdfkit');
const fs = require('fs');

function writePdf(notes, outFile, meta = {}) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 56, info: { Title: notes.title, Author: 'EchoNotes' } });
    const s = fs.createWriteStream(outFile);
    s.on('finish', resolve); s.on('error', reject);
    doc.pipe(s);

    doc.font('Helvetica-Bold').fontSize(22).fillColor('#000').text(notes.title, { align: 'left' });
    doc.font('Helvetica').fontSize(10).fillColor('#555')
      .text(`Generated by EchoNotes${meta.date ? ' · ' + meta.date : ''}${meta.source ? ' · ' + meta.source : ''}`);
    doc.moveDown(0.5).moveTo(56, doc.y).lineTo(539, doc.y).strokeColor('#999').stroke().moveDown(0.8);

    const h = (t) => { doc.moveDown(0.6).font('Helvetica-Bold').fontSize(14).fillColor('#000').text(t).moveDown(0.3); };
    const li = (t) => doc.font('Helvetica').fontSize(11).fillColor('#000').list([t], { bulletRadius: 2, textIndent: 14, bulletIndent: 4 });

    if (notes.keywords.length) {
      h('Key terms');
      doc.font('Helvetica').fontSize(11).text(notes.keywords.join(', '));
    }
    h('Summary');
    notes.summary.forEach(li);
    notes.sections.forEach(sec => { h(sec.heading); sec.bullets.forEach(li); });
    if (notes.glossary.length) {
      h('Glossary');
      notes.glossary.forEach(g => {
        doc.font('Helvetica-Bold').fontSize(11).text(g.term, { continued: true })
          .font('Helvetica').text(' — ' + g.def).moveDown(0.3);
      });
    }
    doc.end();
  });
}
module.exports = { writePdf };
